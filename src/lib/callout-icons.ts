export const CALLOUT_ICONS: Record<string, CalloutIcon> = Object.fromEntries(
  Object.entries(CALLOUT_ICON_NODES).map(([key, { node, color }]) => [
    key,
    { svg: iconToSvg(node), color },
  ])
);

export function getCalloutIcon(type: string): CalloutIcon {
  const icon = CALLOUT_ICONS[type.toLowerCase()];
  if (icon) return icon;
  return {
    svg: iconToSvg([['circle', { cx: '12', cy: '12', r: '10' }], ['path', { d: 'M9.09 9a3 3 0 015.83 1c0 2-3 3-3 3' }], ['path', { d: 'M12 17h.01' }]]),
    color: [150, 150, 150],
  };
}
